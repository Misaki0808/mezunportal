import { chromium } from '@playwright/test';
import { BASE, OUT, measure } from './lib.mjs';
const [pdf] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ storageState: '.tur/student.state.json', viewport: { width: 390, height: 844 } }); const p = await ctx.newPage();
const al = () => p.$$eval('[role=alert],[role=status]', (e) => e.map((x) => x.innerText.trim().replace(/\s+/g, ' ')).filter(Boolean));
await p.goto(BASE + '/profil'); await p.waitForLoadState('networkidle');
const edu = p.getByRole('heading', { name: 'Eğitim' }).locator('xpath=ancestor::section[1]');
await edu.getByRole('button', { name: 'Düzenle' }).click();
const dlg = p.getByRole('dialog'); const f = dlg.getByLabel(/Kurum/); await f.fill('Örnek Üniversitesi'); await dlg.getByLabel(/Bölüm \/ alan/).fill('Bilgisayar Mühendisliği'); await dlg.getByRole('button', { name: 'Kaydet' }).click(); await p.waitForTimeout(1500);
console.log('düzenleme sonrası', JSON.stringify(await al()), 'rozet', await p.getByText('Düzeltildi').count());
await p.screenshot({ path: `${OUT}/prof-duzeltildi-390v.png` });
await p.goto(BASE + '/profil/cv'); await p.waitForLoadState('networkidle');
if (await p.getByLabel(/CV dosyası/).count()) { await p.getByLabel(/CV dosyası/).setInputFiles(pdf); await p.getByRole('button', { name: "CV'yi oku" }).click(); } else console.log('önceki onay kaldığı yerden açıldı');
await p.getByRole('heading', { name: 'Bulunan bilgileri gözden geçir' }).waitFor({ timeout: 60000 }); await p.waitForTimeout(500);
console.log('gruplar', await p.$$eval('h3', (h) => h.map((x) => x.innerText.replace(/\s+/g, ' '))));
const grp = p.getByRole('heading', { name: /Çakışmalar/ }).locator('xpath=ancestor::section[1]');
await grp.scrollIntoViewIfNeeded(); await p.waitForTimeout(300); await p.screenshot({ path: `${OUT}/cv-cakisma-390v.png` });
await grp.getByRole('button', { name: 'Kabul et' }).click(); console.log('kutusuz kabul', JSON.stringify(await grp.locator('[role=alert]').allInnerTexts()));
await grp.getByRole('checkbox', { name: /üzerine yaz/ }).check(); await grp.getByRole('button', { name: 'Kabul et' }).click();
await p.getByRole('button', { name: 'Seçilenleri uygula' }).click(); await p.waitForTimeout(2000);
console.log('sonuç', JSON.stringify(await al()));
await b.close();
