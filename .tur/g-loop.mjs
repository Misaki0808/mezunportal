import { chromium } from '@playwright/test';
const [state, path] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ storageState: `.tur/${state}.state.json` });
const p = await ctx.newPage(); const navs = []; const reqs = [];
p.on('framenavigated', (f) => { if (f === p.mainFrame()) navs.push(f.url().replace('http://localhost:3308', '')); });
p.on('response', (r) => { if (r.request().resourceType() === 'document' || r.request().method() === 'POST') reqs.push(`${r.request().method()} ${r.status()} ${r.url().replace('http://localhost:3308', '')} ${r.headers()['location'] ?? ''}`); });
p.on('console', (m) => reqs.push('console ' + m.type() + ' ' + m.text().slice(0, 150)));
await p.goto('http://localhost:3308' + path).catch((e) => navs.push('ERR ' + e.message.slice(0, 80)));
await p.waitForTimeout(4000);
console.log('navs', navs.length, [...new Set(navs)]); console.log(reqs.slice(0, 15));
await b.close();
